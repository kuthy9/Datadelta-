"""
export.py — Generate a self-contained HTML report (--export flag).

The output is a single .html file with no external dependencies: all CSS
is inlined, no web fonts, no CDN links, no JavaScript. It opens anywhere
(email, Slack, a GitHub PR) and loads nothing from the network.

DESIGN (ink & vermilion)
  One narrow column (max-width 760px) on paper, ink text, 1px rules:
    wordmark "data ▲" + scenario + time
    → verdict (glyph + word in the severity color, plus counts)
    → story lead in a larger serif (with --story)
    → rows summary (tabular figures)
    → findings by layer: clean, schema, integrity, distribution, custom
    → clean summary per side (with --clean)
    → footer with the package version
  Colors are CSS custom properties generated by theme.css_variables():
  light on :root, dark under @media (prefers-color-scheme: dark). Fonts
  are the local stacks from theme.py. No color literal lives here.

WHY AUTOESCAPE?
  Almost every string in the report is derived from the data: column
  names, category values, finding titles, the scenario name, and the
  LLM-written story. A column literally named "<script>...</script>"
  must show up as text, not run as code when a colleague opens the
  file. The template is therefore compiled from an Environment with
  autoescape=True, which HTML-escapes every {{ ... }} expression. The
  only values marked |safe are the CSS variables and font stacks, which
  are constants from theme.py.

The version in the footer comes from datadelta.__version__, the
package's single version source.
"""

