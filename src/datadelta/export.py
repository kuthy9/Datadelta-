# Compiled once at import time; autoescape=True escapes every {{ ... }}.
_ENV      = Environment(autoescape=True)
_TEMPLATE = _ENV.from_string(HTML_TEMPLATE)


def export_html(
    result:      DiffResult,
    output_path: Path,
    *,
    story:       str | None      = None,
    now:         datetime | None = None,
) -> None:
    """
    Render the HTML template and write it to disk.

    story: optional narrative text (from --story) shown as the lead.
    now:   timestamp shown in the header; defaults to the current time
           (tests pass a fixed value).
    """
    from .scenarios import SCENARIO_LABELS

    brand_word, brand_mark = theme.BRAND.rsplit(" ", 1)
    severity = result.summary_severity

    html = _TEMPLATE.render(
        scenario_label = SCENARIO_LABELS.get(result.scenario, result.scenario),
        timestamp      = (now or datetime.now()).strftime("%Y-%m-%d %H:%M"),
        css_light      = theme.css_variables("light"),
        css_dark       = theme.css_variables("dark"),
        font_serif     = theme.FONT_SERIF,
        font_sans      = theme.FONT_SANS,
        font_mono      = theme.FONT_MONO,
        brand_word     = brand_word,
        brand_mark     = brand_mark,
        verdict        = _severity_view(severity),
        counts         = {s: sum(1 for f in result.findings if f.severity == s) for s in ("FAIL", "WARN", "INFO")},
        story          = story.strip() if story else None,
        rows           = _rows_view(result.rows_before, result.rows_after),
        layers         = _layers_view(result.findings),
        cleaning       = _cleaning_view(result.cleaning),
        version        = __version__,
    )

    Path(output_path).write_text(html, encoding="utf-8")


# ─────────────────────────────────────────────────────────────────────────────
# View models — plain dicts, so the template only formats and escapes
# ─────────────────────────────────────────────────────────────────────────────

def _severity_view(severity: str) -> dict:
    return {
        "severity": severity,
        "glyph":    theme.SEVERITY_GLYPH[severity],
        "word":     theme.SEVERITY_WORD[severity],
    }


def _finding_view(finding: Finding) -> dict:
    return {**_severity_view(finding.severity), "title": finding.title, "detail": finding.detail}


def _layers_view(findings: list[Finding]) -> list[dict]:
    """Non-empty layers in display order; schema always (a pass line when unchanged)."""
    layers = []
    for key in LAYERS:
        items = [_finding_view(f) for f in findings if f.layer == key]
        if not items and key == "schema":
            items = [{**_severity_view("PASS"), "title": "no schema changes", "detail": ""}]
        if items:
            layers.append({"key": key, "title": LAYER_TITLES[key], "findings": items})
    return layers


def _rows_view(before: int, after: int) -> dict:
    """Row counts and the change: "▼ 256 · −25.6%", "▲ 12 · +1.2%" or "unchanged"."""
    delta = after - before
    if delta == 0:
        text = "unchanged"
    else:
        glyph = theme.DELTA_UP if delta > 0 else theme.DELTA_DOWN
        text  = f"{glyph} {abs(delta):,}"
        pct   = delta / before if before else math.nan
        if math.isfinite(pct):
            sign = "+" if delta > 0 else theme.MINUS
            text += f" {theme.SEP} {sign}{abs(pct):.1%}"
    return {"before": f"{before:,}", "after": f"{after:,}", "delta": text}


def _cleaning_view(cleaning: dict | None) -> list[dict]:
    """One row per cleaned side: cells changed, rows dropped, retyped columns."""
    if not cleaning:
        return []
    sides = []
    for side in ("before", "after"):
        report = cleaning.get(side)
        if report is None:
            continue
        stats   = report["stats"]
        retyped = ", ".join(f"{col} {theme.ARROW} {kind}" for col, kind in stats["columns_retyped"].items())
        sides.append({
            "side":          side,
            "cells_changed": f"{stats['cells_changed']:,}",
            "rows_dropped":  f"{stats['rows_before'] - stats['rows_after']:,}",
            "retyped":       retyped or "none",
        })
    return sides
